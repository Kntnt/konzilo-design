const LOGO_LIMIT = 24000;
function decodeDataUri(uri) {
  const comma = uri.indexOf(',');
  const head = uri.slice(5, comma);
  const data = uri.slice(comma + 1);
  if (!/;base64$/i.test(head)) return { type: head.split(';')[0], text: decodeURIComponent(data) };
  const bytes = Uint8Array.from(atob(data), (c) => c.charCodeAt(0));
  return { type: head.split(';')[0], text: new TextDecoder().decode(bytes), size: bytes.length };
}
function logoWords(label, logo, file) {
  if (!logo) return null;
  if (file) return `- **${label}:** \`${file}\`, beside this file.`;
  if (!logo.startsWith('data:')) return `- **${label}:** the file \`${logo}\`, beside the design file this was made from. It is not inside this file; ask for it, and never draw a logo of your own.`;
  const { type, text, size = text.length } = decodeDataUri(logo);
  if (type !== 'image/svg+xml') return `- **${label}:** a ${type.replace('image/', '').toUpperCase()} image of ${Math.round(size / 1024)} KB, held in the design file and not carried here. Ask for it, and never draw a logo of your own.`;
  if (text.length > LOGO_LIMIT) return `- **${label}:** an SVG of ${Math.round(text.length / 1024)} KB, too large to carry here. Ask for it, and never draw a logo of your own.`;
  const fence = '`'.repeat(Math.max(3, ...[...text.matchAll(/`+/g)].map(([run]) => run.length + 1)));
  return `- **${label}:** this SVG, to be saved as a file as it stands:\n\n${fence}svg\n${text.trim()}\n${fence}`;
}
