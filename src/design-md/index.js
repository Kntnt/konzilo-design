function yaml(value, indent = 0) {
  const pad = ' '.repeat(indent);
  return Object.entries(value)
    .filter(([, item]) => item !== undefined)
    .map(([key, item]) => (item !== null && typeof item === 'object'
      ? `${pad}${key}:\n${yaml(item, indent + 2)}`
      : `${pad}${key}: ${yamlValue(item)}`))
    .join('\n');
}
