const scaleWords = ({ breakpoints: { min, max }, ratio, 'body-size': body }) => min === max
  ? `The base is ${ratio.min} and the body size ${rem(body.min)} in windows below ${windowWords(max)}, and ${ratio.max} and ${rem(body.max)} from there.`
  : `The base is ${ratio.min} and the body size ${rem(body.min)} up to a window of ${windowWords(min)}, ${ratio.max} and ${rem(body.max)} from ${windowWords(max)}, and each follows a straight line in between.`;
function exactScale({ breakpoints: { min, max }, ratio, 'body-size': body }) {
  if (min === max) return '';
  const start = Math.min(min, max - 1);
  const n = (x) => String(Number(x.toFixed(4)));
  return `\n\nThe \`clamp()\` is a straight line between the two ends. The true scale, within a pixel or two of it, is \`body × base^step\` with body and base each on their straight line; where a browser has \`pow()\` and \`atan2()\`, write it as:

\`\`\`css
/* t runs from 0 in a ${windowWords(min)} window to 1 in a ${windowWords(max)} one. */
--t: clamp(0, (tan(atan2(100vw, 1rem)) - ${n(start / 16)}) / ${n((max - start) / 16)}, 1);
--body: calc(${rem(body.min)} + ${rem(body.max - body.min)} * var(--t));
--base: calc(${ratio.min} + ${n(ratio.max - ratio.min)} * var(--t));
font-size: calc(var(--body) * pow(var(--base), STEP)); /* at least 0.75rem below the body */
\`\`\``;
}

const LICENCES = [[/SIL Open Font License/i, 'the SIL Open Font License 1.1'], [/Apache License/i, 'the Apache License 2.0'], [/MIT License/i, 'the MIT License'], [/Ubuntu Font Licen[cs]e/i, 'the Ubuntu Font Licence']];
function licenceOf(face) {
  try {
    const text = readFileSync(new URL(`../fonts/${face.licence}`, import.meta.url), 'utf8');
    return LICENCES.find(([pattern]) => pattern.test(text))?.[1] || 'a free licence';
  } catch {
    return 'a free licence';
  }
}
// Where to fetch a face's files directly. A face the library takes from Google Fonts lies in Google's font repository,
// in a folder named for its licence and its family; any other comes from its designers' own release or repository.
const LICENCE_FOLDERS = [[/Apache/, 'apache'], [/Ubuntu/, 'ufl'], [/./, 'ofl']];
export function downloadOf(face, licence) {
  if (!/fonts\.google\.com\/specimen\//.test(face.source)) {
    return /\/releases\/tag\//.test(face.source)
      ? `its release, ${face.source}, whose attached files are the download`
      : `its designers' repository at the version the library uses, ${face.source}`;
  }
  const folder = LICENCE_FOLDERS.find(([pattern]) => pattern.test(licence))[1];
  return `Google's font repository, https://github.com/google/fonts/tree/main/${folder}/${face.family.toLowerCase().replace(/[^a-z0-9]/g, '')}, which holds the variable font files and their licence`;
}
const AXIS_WORDS = {
  wght: null,
  wdth: null,
  opsz: '`opsz`, its optical size, which the browser sets from the font size by itself (`font-optical-sizing: auto`, the default) unless a style\'s `fontVariation` names it',
};
function faceWords(family, assets) {
  const face = faceOf(family);
  if (!face) return `- **${family}:** the system's own typeface, so there is nothing to serve.`;
  const licence = licenceOf(face);
  const range = [`\`font-weight: ${face.weight}\``, face.stretch && `\`font-stretch: ${face.stretch}\``].filter(Boolean).join(' and ');
  const italic = face.italic ? 'Its italic is a file of its own.' : face.slant ? 'Its italic comes through its slant axis.' : 'It has no italic, so it stays upright.';
  const others = Object.keys(face.axes || {}).filter((axis) => AXIS_WORDS[axis] !== null);
  const axes = others.length ? ` Besides weight${face.stretch ? ' and width' : ''} it has ${list(others.map((axis) => AXIS_WORDS[axis] || `\`${axis}\`, at its default unless a style's \`fontVariation\` sets it`))}.` : '';
  const own = assets?.fonts?.[face.family];
  const where = own ? `free to serve, in ${list(own.files.map((name) => `\`${name}\``))}, with its licence in \`${own.licence}\`` : `free to download and to serve, from ${downloadOf(face, licence)}`;
  return `- **${face.family}**, version ${face.version}, under ${licence}: ${where}. Use the variable font, declared with ${range}. ${italic}${axes}`;
}

function typeSection({ resolved: r, project, assets }) {
  const { breakpoints } = r['type-scale'];
  const rows = STYLES.map(([name, style]) => {
    const recipe = r.type[style];
    return `| ${name} | ${familyOf(stackOfStyle(style, r.typefaces))} | ${recipe.step} | \`${sizeCss(recipe)}\` | ${USES[name]} |`;
  }).join('\n');
  const staged = STYLES.filter(([, style]) => r.type[style].features)
    .map(([name, style]) => ({ name, value: r.type[style].features.value, from: r.type[style].features['from-window'] }));
  // One line per setting and window, since a typeface's tuning switches on where its size passes a threshold.
  const groups = new Map();
  for (const { name, value, from } of staged) {
    const key = `${value}\n${from}`;
    groups.set(key, [...(groups.get(key) || []), name]);
  }
  const features = staged.length
    ? `\n- **Features:** where \`fontFeature\` is set it is part of the look, though not in every window:\n${[...groups].map(([key, names]) => {
      const [value, from] = key.split('\n');
      return `  - \`font-feature-settings: ${value}\` in ${list(names)}, ${Number(from) > 0 ? `from a window of ${windowWords(Number(from))}, \`@media (min-width: ${rem(Number(from))})\`` : 'in every window'}.`;
    }).join('\n')}`
    : '';
  const faces = [...new Set(Object.values(r.typefaces).map(familyOf))];
  const emphasis = r.type['heading-6'].weight;
  return `## Typography
${why(project.explanations?.typefaces)}${why(project.explanations?.['type-scale'])}
| Style | Typeface | Step | \`font-size\` | Used for |
|---|---|---|---|---|
${rows}

Weight, line height, letter spacing, features and axes are in the \`typography\` tokens, whose \`fontSize\` holds the size in a wide window. Each size is the body size times a base to the power of the style's step. ${scaleWords(r['type-scale'])} The \`font-size\` column holds this as CSS: headings close up on a phone and open out on a wide screen, so use it rather than breakpoints of your own.${exactScale(r['type-scale'])}

- **Display** is for what is larger than the first heading, and never for a second heading or smaller.
- **Labels** are always in capitals, with tabular digits, and no text is smaller than 0.75rem (12 px).
- **The emphasis weight** is ${emphasis}, the h6 style's: buttons, menus, table heads and strong text take it.${features}
- **Axes:** where \`fontVariation\` is set, apply it; its width (\`wdth\`) goes in \`font-stretch\` as a percentage.
- **Italics** come from the typeface. Never let a browser slant one (\`font-synthesis-style: none\`).

The typefaces are free variable fonts. Serve them from the site itself, never from a font service, with \`font-display: swap\`:

${faces.map((family) => faceWords(family, assets)).join('\n')}${assets?.fonts && Object.keys(assets.fonts).length ? `\n\n\`${assets.css}\` holds their \`@font-face\` rules, with addresses relative to that folder.` : ''}`;
}

function layoutSection({ resolved: r, project }) {
  const space = r.space.roles;
  const css = (value) => `\`${value.css}\``;
  return `## Layout
${why(project.explanations?.['space-shape'])}
A page is a header, a vertical sequence of Bands, and a footer. Nothing lies directly on the page. A Band's background runs edge to edge, while its content stays in the content area, so the header, the footer and every Band line up.

- **Content area:** \`min(100% − 2 × side margin, Wide)\`, centred, where **Wide** is ${rem(r.layout.wide)} (${r.layout.wide} px).
- **Side margin:** ${css(r.layout['side-margin'])}.
- **Narrow** is ${rem(r.layout.narrow)} (${r.layout.narrow} px), the measure for running text.
- **Widths an element may take:** \`narrow\`; \`wide\`, the content area; \`full\`, the window's edge to edge (\`100vw\`); \`bleed-start\` and \`bleed-end\`, from one edge of the content area to the window's other edge, \`(100vw + content area) / 2\` wide.

Space is fluid like type. Each role grows in a straight line from a ${windowWords(320)} window to a ${windowWords(1440)} one, and the \`spacing\` tokens hold its wide end:

- **Within a component** (\`component-gap\`): ${css(space['component-gap'])}.
- **Between columns** (\`column-gap\`): ${css(space['column-gap'])}.
- **Inside a card or box on a Surface** (\`plate\`): ${css(space.plate)}.
- **Above and below a Band** (\`band\`): ${css(space.band)}.
- **Between two Bands on the same Surface** (\`band-run\`): ${css(space['band-run'])}. The first loses its end space and the second starts with this, so a change of Surface gets more air than a run of one.

**Where running text stands.** Long text lies in a Reading Area inside a Band, as a column at most Narrow wide. With nothing beside it, the column is centred in the content area. With an Aside, for a table of contents or notes, the column lies against the content area's start edge and the Aside takes the rest at the end, after the column gap, which suits most pages; it may also be the other way round. The Aside is at least ${rem(r.layout['aside-min'])} wide: where it would be narrower, the area is one column, with the Aside's content before the text, or after it. In two columns the Narrow column stays where it is even on a page whose Aside is empty, so pages of one kind align alike.`;
}

function elevationSection({ inputs, resolved: r, project }) {
  const on = inputs.shadow.strength > 0;
  const light = r.surfaces.page.light.shadow, dark = r.surfaces.page.dark.shadow;
  const same = Object.keys(light).every((level) => light[level] === dark[level]);
  const always = kindsOf(r).filter((kind) => kind !== 'page' && r.surfaces[kind].light.shadow.header === dark.header && light.header !== dark.header);
  const USE = {
    header: 'the header, once page content has scrolled under it',
    'header-panel': 'the header while one of its panels is open',
    panel: 'the megamenu, the search box, the language list, a dialog and the consent banner',
    page: 'the page over the footer',
    box: 'a card on a Surface',
    'box-lifted': 'a linked card on a Surface, while hovered or focused',
  };
  const levels = Object.keys(light).map((level) => `- **${level}**, ${USE[level] || 'a layer of its own'}: ${light[level] === 'none' ? 'none' : `\`${light[level]}\``}${same || light[level] === 'none' ? '' : `; in dark mode \`${dark[level]}\``}.`).join('\n');
  const darkWords = same ? 'The values are the same in both modes and on every Surface.'
    : `A shadow follows the Surface of what casts it. The dark-mode values, black at about three times the opacity, also hold in light mode on ${list(always.map((kind) => `\`${kind}\``)) || 'the Surfaces dark in both modes'}, which are dark in both modes. The page's shadow over the footer follows what it falls on instead, the footer's first band: on a band dark in light mode it takes the dark values in light mode too, or it would hardly show. A shadow never turns light.`;
  return `## Elevation & Depth
${why(project.explanations?.shadow)}
There are three layers, from the top: the header with the panels it opens, the page, and the footer. The upper layer casts the shadow on the lower, never the reverse, and only where something lies under it.

${on ? `Shadows, each for its use, in light mode and in dark mode:\n\n${levels}\n\n${darkWords} A layer or box without a shadow is set off by a 1 px hairline in \`border\`, or by its own Surface.` : 'This design has no shadows. Hierarchy comes from the Surfaces and from 1 px hairlines in the `border` role, so do not add any.'}`;
}

// The frame is the design's own solid line around buttons and cards on a Surface, 0-3 px; say plainly when it is none.
function frameWords(r) {
  if (!r.frame.width) return '**Frame:** this design has none (its width is 0). Where a recipe mentions the frame, leave it out: a filled button has no ring and a card on a Surface no border.';
  if (frameFollows(r.surfaces, 'border')) return `**Frame:** a quiet ${r.frame.width} px solid line, in each plate's own \`border\` colour, in the tokens \`<surface>-frame\` and \`dark-<surface>-frame\`, so it follows the Surface and the mode: a card on a Surface takes its own Surface's \`border\` as its border. A filled button, a small plate on its Surface, takes its own \`button-background-hover\`, the step beside its fill, as an inset ring as wide as the frame; an unfilled button's ring takes its width, still in \`border-strong\`.`;
  const followsText = frameFollows(r.surfaces, 'text');
  return `**Frame:** a ${r.frame.width} px solid line, in ${followsText ? 'the `text` colour of the Surface it stands on' : 'one colour of its own'}, in the tokens \`<surface>-frame\` and \`dark-<surface>-frame\`. A filled button takes it as an inset ring as wide as the frame; an unfilled button's ring takes its width, still in \`border-strong\`; a card on a Surface takes it as its border.`;
}

function shapeSection({ resolved: r }) {
  return `## Shapes

Controls such as buttons, fields, callouts and menus have a corner radius of ${rem(r.radius.control)}, and cards, pictures, boxes and panels ${rem(r.radius.card)}. That is ${cornersIn(r.radius.card)}. Two shapes are fixed whatever the design: pills (category tags, filter toggles, a switch's track) have a radius of 2em, and round controls (a video's play button, a switch's knob, the consent button) are circles.

A picture inside a card on a Surface runs flush to the card's edges and takes its outer corners; a picture that reaches the window's edge loses its radius on that side.

${frameWords(r)}`;
}

