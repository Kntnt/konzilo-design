// Writes a design file as DESIGN.md: the open format for describing a design system to an AI agent
// (https://github.com/google-labs-code/design.md). Tokens are normative and come from `resolved`; the
// prose says how to use them, since that is what decides the quality of what an agent makes.
import { COMPONENT_GROUPS, NOT_COMPONENTS } from './components.js';
import { faceOf } from '../fonts/catalog.js';

export const MARKER = 'Generated by the Konzilo Design System';
const CHECKED_KINDS = ['page', 'raised', 'tint', 'tint-secondary', 'tint-tertiary', 'brand', 'inverse', 'accent'];
const ROLES = ['background', 'background-alt', 'background-hover', 'text', 'text-muted', 'border', 'border-strong', 'link', 'accent', 'focus', 'button-background', 'button-text', 'button-background-hover'];
const STYLES = [['display', 'display'], ['h1', 'heading-1'], ['h2', 'heading-2'], ['h3', 'heading-3'], ['h4', 'heading-4'], ['h5', 'heading-5'], ['h6', 'heading-6'], ['lead', 'lead'], ['body', 'body'], ['small', 'small'], ['label', 'label'], ['code', 'mono']];
const KIND_JOBS = {
  page: 'the page itself and most bands',
  raised: 'a card or panel lifted from its background',
  tint: 'a quiet band or card in the primary colour',
  'tint-secondary': 'a quiet band or card in the secondary colour',
  'tint-tertiary': 'a quiet band or card in the tertiary colour',
  brand: 'a strong band in the primary colour',
  inverse: 'a strong band in dark grey',
  accent: 'a strong band for emphasis',
};

const familyOf = (stack) => stack.split(',')[0].trim().replace(/^["']|["']$/g, '');
const px = (value) => `${value}px`;
const yamlValue = (value) => (typeof value === 'number' ? String(value) : JSON.stringify(value));
function yaml(value, indent = 0) {
  const pad = ' '.repeat(indent);
  return Object.entries(value)
    .filter(([, item]) => item !== undefined)
    .map(([key, item]) => (item !== null && typeof item === 'object'
      ? `${pad}${key}:\n${yaml(item, indent + 2)}`
      : `${pad}${key}: ${yamlValue(item)}`))
    .join('\n');
}

const variationOf = (recipe) => {
  const axes = { ...(recipe.stretch !== undefined ? { wdth: recipe.stretch } : {}), ...recipe.variation };
  return Object.keys(axes).length ? Object.entries(axes).map(([axis, value]) => `"${axis}" ${value}`).join(', ') : undefined;
};
const stackOfStyle = (style, typefaces) => (style === 'display' ? typefaces.display
  : style === 'heading-1' ? typefaces['heading-1'] || typefaces.heading
  : style.startsWith('heading-') ? typefaces.heading
  : style === 'label' ? typefaces.label
  : style === 'mono' ? typefaces.monospace
  : typefaces.main);

function tokens(file) {
  const { resolved: r, inputs } = file;
  const colors = {};
  const brand = inputs['brand-colors'];
  for (const rank of ['primary', 'secondary', 'tertiary']) if (brand[rank]) colors[rank] = brand[rank];
  colors.neutral = r.ramps.gray[500];
  for (const [name, ramp] of Object.entries(r.ramps)) for (const [step, value] of Object.entries(ramp)) colors[`${name}-${step}`] = value;
  const kinds = CHECKED_KINDS.filter((kind) => r.surfaces[kind]);
  for (const [prefix, mode] of [['', 'light'], ['dark-', 'dark']])
    for (const kind of kinds)
      for (const role of ROLES) colors[`${prefix}${kind}-${role}`] = r.surfaces[kind][mode].roles[role];
  for (const status of ['info', 'success', 'warning', 'error']) {
    colors[status] = r.surfaces.page.light.roles[status];
    colors[`dark-${status}`] = r.surfaces.page.dark.roles[status];
  }
  const typography = Object.fromEntries(STYLES.map(([name, style]) => {
    const recipe = r.type[style];
    return [name, {
      fontFamily: familyOf(stackOfStyle(style, r.typefaces)),
      fontSize: px(recipe.size.max),
      fontWeight: recipe.weight,
      lineHeight: recipe['line-height'],
      letterSpacing: `${recipe['letter-spacing']}em`,
      fontFeature: recipe.features?.value,
      fontVariation: variationOf(recipe),
    }];
  }));
  const spacing = {
    ...Object.fromEntries(Object.entries(r.space.steps).map(([step, { max }]) => [`step-${step}`, px(max)])),
    ...Object.fromEntries(Object.entries(r.space.roles).map(([role, { max }]) => [role, px(max)])),
    'content-wide': px(r.layout.wide),
    'content-narrow': px(r.layout.narrow),
    'aside-min': px(r.layout['aside-min']),
    'side-margin': px(r.layout['side-margin'].max),
  };
  const fromPage = (role) => `{colors.page-${role}}`;
  const components = {
    'button-primary': { backgroundColor: fromPage('button-background'), textColor: fromPage('button-text'), rounded: '{rounded.control}', typography: '{typography.body}', padding: '0.8em' },
    'button-primary-hover': { backgroundColor: fromPage('button-background-hover') },
    'button-on-brand': { backgroundColor: '{colors.brand-button-background}', textColor: '{colors.brand-button-text}', rounded: '{rounded.control}' },
    card: { backgroundColor: '{colors.raised-background}', textColor: '{colors.raised-text}', rounded: '{rounded.card}', padding: '{spacing.plate}' },
    'card-tint': { backgroundColor: '{colors.tint-background}', textColor: '{colors.tint-text}', rounded: '{rounded.card}', padding: '{spacing.plate}' },
    'input-field': { backgroundColor: fromPage('background'), textColor: fromPage('text'), rounded: '{rounded.control}', height: '44px' },
    eyebrow: { textColor: fromPage('text-muted'), typography: '{typography.label}' },
  };
  return {
    version: 'alpha',
    name: file.project.name || 'Design system',
    description: `The design system of ${file.project.name || 'this site'}, made with the Konzilo Design System.`,
    colors,
    typography,
    rounded: { control: px(r.radius.control), card: px(r.radius.card) },
    spacing,
    components,
  };
}

const why = (text) => (text?.trim() ? `\n${text.trim()}\n` : '');
const cornersIn = (card) => (card === 0 ? 'square corners' : card < 6 ? 'almost square corners' : card < 16 ? 'discreetly rounded corners' : 'clearly rounded corners');
const airIn = (density) => (density < 30 ? 'compact' : density < 70 ? 'moderately airy' : 'loose and airy');
const depthIn = ({ strength, hardness }) => (strength === 0 ? 'flat, with hairlines instead of shadows' : hardness >= 100 ? 'set off by hard, solid offset shadows' : hardness >= 50 ? 'set off by crisp shadows' : 'set off by soft shadows');

function overview({ project, inputs, resolved: r }) {
  const faces = [...new Set(Object.values(r.typefaces).map(familyOf))];
  const colours = Object.keys(inputs['brand-colors']).length;
  return `## Overview
${project.brief?.trim() ? `\n${project.brief.trim()}\n` : ''}
The design has ${colours === 1 ? 'one brand colour' : `${colours} brand colours`} and a grey scale. ${faces.length === 1 ? `Its typeface is ${faces[0]}` : `Its typefaces are ${faces.slice(0, -1).join(', ')} and ${faces.at(-1)}`}. It has ${cornersIn(r.radius.card)}, its spacing is ${airIn(inputs['density-profile'])}, and it is ${depthIn(inputs.shadow)}.

The tokens above are exact, and every value was generated from one small set of decisions, so they belong together. Use them as they stand and do not add colours, sizes or typefaces. Pages are built from the components listed below. Light and dark mode are both part of the design.

On a site, every token is also a CSS variable with the prefix \`--kn-\`, such as \`--kn-text\` or \`--kn-type-body-size\`. Prefer the variables to literal values: they follow the Surface, the mode and the window by themselves.`;
}

function colourSection({ inputs, resolved: r, project }) {
  const kinds = CHECKED_KINDS.filter((kind) => r.surfaces[kind]);
  const ranks = ['primary', 'secondary', 'tertiary'].filter((rank) => inputs['brand-colors'][rank]);
  return `## Colors
${why(project.explanations?.colour)}
${ranks.map((rank) => `- **${rank[0].toUpperCase()}${rank.slice(1)} (${inputs['brand-colors'][rank]}):** ${{ primary: 'the main identity and the strongest backgrounds', secondary: 'a supporting colour for accents and a tint of its own', tertiary: 'one more tint, for grouping content' }[rank]}.`).join('\n')}
- **Neutral:** a grey scale for text, borders and quiet backgrounds.

Each brand colour and the grey have a ramp from 100, lightest, to 950, darkest, in the tokens \`primary-100\` to \`gray-950\`.

**Surfaces are how colour is used.** A Surface is a background together with the colours that work on it. Every section and card stands on one, and the text, links, borders and buttons on it take their colours from that same Surface:

${kinds.map((kind) => `- **${kind}:** ${KIND_JOBS[kind]}${r.surfaces[kind].light.polarity === 'dark' && r.surfaces[kind].dark.polarity === 'dark' ? ', dark in both modes' : ''}.`).join('\n')}

The tokens are named \`<surface>-<role>\` for light mode and \`dark-<surface>-<role>\` for dark mode, for example \`tint-text\` and \`dark-tint-text\`. The roles are ${ROLES.map((role) => `\`${role}\``).join(', ')}. Every text and background pair within a Surface has passed a WCAG contrast check in both modes (status: ${r['contrast-check'].status}). A pair taken across two Surfaces has not, so never mix them. On a site, setting \`data-kn-surface="tint"\` on an element makes the \`--kn-*\` colour variables inside it follow that Surface.`;
}

const scaleWords = ({ breakpoints: { min, max }, ratio, 'body-size': body }) => min === max
  ? `The base is ${ratio.min} and the body size ${body.min} px in windows below ${max} px, and ${ratio.max} and ${body.max} px from there.`
  : `The base is ${ratio.min} and the body size ${body.min} px up to a window of ${min} px, ${ratio.max} and ${body.max} px from ${max} px, and each follows a straight line in between.`;

function typeSection({ resolved: r, project }) {
  const { breakpoints } = r['type-scale'];
  const rows = STYLES.map(([name, style]) => {
    const recipe = r.type[style];
    return `| ${name} | ${familyOf(stackOfStyle(style, r.typefaces))} | ${recipe.size.min === recipe.size.max ? recipe.size.max : `${recipe.size.min}–${recipe.size.max}`} px | ${recipe.weight} | ${recipe['line-height']} | ${recipe['letter-spacing']}em |`;
  }).join('\n');
  const faces = [...new Set(Object.values(r.typefaces).map(familyOf))].map(faceOf).filter(Boolean);
  const sources = faces.map((face) => `- **${face.family}**, version ${face.version}: ${face.source}. Italic: ${face.italic ? 'a file of its own' : face.slant ? 'through its slant axis' : 'none, so it stays upright'}.`).join('\n');
  return `## Typography
${why(project.explanations?.typefaces)}${why(project.explanations?.['type-scale'])}
| Style | Typeface | Size, ${breakpoints.min} to ${breakpoints.max} px window | Weight | Line height | Letter spacing |
|---|---|---|---|---|---|
${rows}

The \`fontSize\` tokens hold the size in a wide window. Each size is the body size times a base to the power of the style's step. ${scaleWords(r['type-scale'])} Use \`--kn-type-<style>-size\`, which holds this and falls back on a \`clamp()\` in a browser without \`pow()\`. Headings therefore close up on a phone and open out on a wide screen.

- **Display** is for what is larger than the first heading, and never for a second heading or smaller.
- **Labels** are eyebrows, metadata and category pills. They are always in capitals, and no text is smaller than 12 px.
- **Features and axes:** where \`fontFeature\` or \`fontVariation\` is set it is part of the look, so apply it. Width goes in \`font-stretch\`; each style has \`--kn-type-<style>-stretch\` and \`--kn-type-<style>-variation\`.
- **Italics** come from the typeface. Never let a browser slant one (\`font-synthesis-style: none\`).

The typefaces are free variable fonts, served by the site itself:

${sources}`;
}

function layoutSection({ resolved: r, project }) {
  const space = r.space.roles;
  const range = ({ min, max }) => `${min}–${max} px`;
  return `## Layout
${why(project.explanations?.['space-shape'])}
A page is a header, a vertical sequence of Bands, and a footer. Nothing lies directly on the page. A Band's background runs edge to edge, while its content stays in the content area, \`min(window − 2 × side margin, Wide)\`, so the header, the footer and every Band line up.

- **Wide (${r.layout.wide} px)** is the content area. **Narrow (${r.layout.narrow} px)** is the measure for running text. **Full** is edge to edge.
- **Side margin:** ${range(r.layout['side-margin'])}, growing with the window.
- **Space within a component** (\`component-gap\`): ${range(space['component-gap'])}. **Between columns** (\`column-gap\`): ${range(space['column-gap'])}. **Inside a card** (\`plate\`): ${range(space.plate)}.
- **Above and below a Band** (\`band\`): ${range(space.band)}. **Between Bands with the same background** (\`band-run\`): ${range(space['band-run'])}.

Space is fluid like type: read \`--kn-space-<role>\` rather than a fixed length. The \`spacing\` tokens hold the values in a wide window. Lengths on a site are in rem, so a visitor's text size setting holds.`;
}

function elevationSection({ inputs, resolved: r, project }) {
  const on = inputs.shadow.strength > 0;
  const shadows = Object.entries(r.shadow).map(([level, value]) => `- **${level}:** \`${value}\``).join('\n');
  return `## Elevation & Depth
${why(project.explanations?.shadow)}
There are three layers, from the top: the header with the panels it opens, the page, and the footer. The upper layer casts the shadow on the lower, never the reverse.

${on ? `Shadows, in light mode:\n\n${shadows}\n\nOn a dark Surface a shadow stays dark. Read \`--kn-shadow-<level>\`.` : 'This design has no shadows. Hierarchy comes from the Surfaces and from hairlines in the `border` role, so do not add any.'}${r.frame.width ? `\n\nComponents have a ${r.frame.width} px solid frame.` : ''}`;
}

function shapeSection({ resolved: r }) {
  return `## Shapes

Controls such as buttons and fields have a corner radius of ${r.radius.control} px, and cards and pictures ${r.radius.card} px. That is ${cornersIn(r.radius.card)}, and they are the only two radii in the design.`;
}

const SHOWS = { 'link-menu': 'a link menu', language: 'a language switcher', search: 'a search icon', cta: 'a call-to-action button' };
const TRAIL_MARKS = { slash: '/', chevron: '›', arrow: '→', dot: '·' };
function trailWords(b) {
  if (!b?.show) return '- **Breadcrumb Navigation:** none on this design\'s pages.';
  const first = { word: 'the word Home', name: 'the site\'s name', icon: 'a house icon' }[b.home];
  return `- **Breadcrumb Navigation:** on every page but the start page, ${b.placement === 'own-band' ? 'in a thin Band of its own directly under the header' : 'at the top of the first Band, above its heading'}. It begins with ${first}, its steps are parted by ${TRAIL_MARKS[b.separator]}, and it ${b.current ? 'ends with the current page as plain text' : 'ends with the page above'}. ${b.narrow === 'parent' ? 'On a phone only the link one level up shows.' : 'On a phone the whole trail wraps.'}`;
}
const HERO_SHARES = { third: 'a third', half: 'half', 'two-thirds': 'two thirds', full: 'all' };
function heroWords(h) {
  if (!h) return '';
  const colour = h.surface === 'none' ? 'no background of its own' : `the ${h.surface} Surface`;
  const ground = h.picture === 'behind' ? `a picture behind the text, under a ${h.overlay} overlay` : h.picture === 'beside' ? `a picture beside the text, on ${colour}` : colour;
  const place = h.height === 'third' || h.place === 'center' ? 'centred' : 'at the bottom';
  return `\n- **Hero:** by default ${ground}, taking ${HERO_SHARES[h.height]} of the screen, with its text ${place} and its heading in the ${h.type === 'display' ? 'display' : 'first heading'} style. A page may depart from this.`;
}
function frameWords({ header: h, footer: f, page: p, breadcrumbs: b, hero }) {
  const items = Object.keys(SHOWS).filter((key) => h[key]).map((key) => SHOWS[key]);
  const button = { word: 'a menu button with the word and a chevron', icon: 'a menu button with a hamburger icon', off: 'a menu button only when items give way' }[h['menu-button']];
  const attached = h.attachment === 'flow' ? 'It scrolls away with the page.' : `It sticks to the top of the window${h.autohide ? ' and slides away while scrolling down' : ''}.${h.start === 'under' ? ' The page starts under it, and it is transparent at the top.' : ''}`;
  return `### This design's frame

- **Header:** arrangement ${h.arrangement}, on the ${h.surface} Surface, showing ${[...items, button].join(', ')}. ${attached} The search box is on the ${h['search-surface']} Surface${h['search-blur'] ? ', over a blurred page' : ''}.
- **Footer:** the \`${f.model}\` model on the ${f.surface} Surface, ${f.attachment === 'reveal' ? 'revealed under the page' : 'in the flow'}. Lines between rows: ${f['horizontal-rules'] ? 'yes' : 'no'}; between columns: ${f['vertical-rule'] ? 'yes' : 'no'}.
- **Page:** ${p.shadow ? 'it casts a shadow on the footer' : 'no shadow on the footer'}${p['edge-line'] ? ', with a line at its bottom edge' : ''}.
${trailWords(b)}${heroWords(hero)}`;
}
function componentSection({ project, resolved }) {
  const groups = COMPONENT_GROUPS.map(([group, items]) => `### ${group}\n\n${items.map(([name, job]) => `- **${name}:** ${job}`).join('\n')}`).join('\n\n');
  return `## Components
${why(project.explanations?.components)}
Build pages from these, and do not make new ones where one of them will do. The tokens above give the look of the most common ones; the rest follow from the Surfaces and the type styles. A site using the library takes them as Astro components from \`@kntnt/konzilo-design/components\` and as classes prefixed \`kn-\`.

${resolved.header ? `${frameWords(resolved)}\n\n` : ''}${groups}`;
}

function rulesSection() {
  return `## Do's and Don'ts

- Do build every page as a header, Bands and a footer, and put each Band on a Surface.
- Do take every colour on a Surface from that same Surface, and check the page in both light and dark mode.
- Do let adjacent Bands differ in Surface to give a page rhythm; use the strong Surfaces, \`brand\`, \`inverse\` and \`accent\`, sparingly.
- Do use one first heading per page, and keep running text in the Narrow measure.
- Do keep text on the type scale, and use the fluid sizes rather than breakpoints of your own.
- Do work at both a phone's width and a wide screen, since the narrow and wide type scales differ.
- Don't use a display style for a second heading or smaller.
- Don't add colours, typefaces, radii or shadows that are not in this file.
- Don't invent components: this design system deliberately has no ${NOT_COMPONENTS.join(', ')}.
- Don't slant or embolden a typeface artificially.
- Don't load fonts or embedded content from third parties without consent: an Embed waits for the visitor's consent.`;
}

export function designMd(file, sourceName = 'the design file') {
  return `---
${yaml(tokens(file))}
---

<!-- ${MARKER} from ${sourceName}. Change the design and export again rather than editing this file. -->

${[overview(file), colourSection(file), typeSection(file), layoutSection(file), elevationSection(file), shapeSection(file), componentSection(file), rulesSection()].join('\n\n').replace(/\n{3,}/g, '\n\n')}
`;
}
